"""Generate the LaTeX fragments that paper/paper.tex \\input{}s.

The paper's prose is static; every number, table and figure comes from the
results file through this module, so the PDF can never drift from the data.

Fragments written to paper/generated/:
    macros.tex          scalar facts as \\MLS... macros
    ranking_table.tex   full ranking with per-component contributions
    headtohead_table.tex  Paris vs Amsterdam, metric by metric
    model_table.tex     effective weights actually used
    contributions_figure.tex  stacked-bar figure (plain TikZ)
    findings.tex        factual summary sentences
    coverage.tex        exclusions, unscored locations, source errors
"""

from __future__ import annotations

from pathlib import Path
from typing import Optional

_ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
    "²": r"\textsuperscript{2}",
    "–": "--",
    "—": "---",
    "≥": r"$\geq$",
    "≤": r"$\leq$",
    "×": r"$\times$",
    "°": r"\textdegree{}",
}


def tex_escape(text) -> str:
    """Escape arbitrary text for use in LaTeX body text."""
    return "".join(_ESCAPES.get(ch, ch) for ch in str(text))


def fmt(value: Optional[float], digits: int = 1) -> str:
    """Format a number, or an em-dash-like marker when missing."""
    if value is None:
        return "--"
    if digits == 0:
        return f"{value:,.0f}".replace(",", r"\,")
    return f"{value:.{digits}f}"


def write_fragments(results: dict, out_dir: Path) -> list:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    fragments = {
        "macros.tex": macros(results),
        "ranking_table.tex": ranking_table(results),
        "headtohead_table.tex": headtohead_table(results),
        "model_table.tex": model_table(results),
        "contributions_figure.tex": contributions_figure(results),
        "findings.tex": findings(results),
        "coverage.tex": coverage(results),
    }
    written = []
    for name, body in fragments.items():
        path = out_dir / name
        path.write_text("% AUTO-GENERATED by src/reporting/latex.py - do not edit by hand.\n" + body + "\n",
                        encoding="utf-8")
        written.append(path)
    return written


# -- helpers -----------------------------------------------------------------

def _scored(results: dict) -> list:
    return sorted((l for l in results["locations"] if l["scored"]), key=lambda l: l["rank"])


def _by_id(results: dict) -> dict:
    return {l["id"]: l for l in results["locations"]}


def _macro(name: str, value) -> str:
    return f"\\newcommand{{\\MLS{name}}}{{{value}}}"


# -- fragments ---------------------------------------------------------------

def macros(results: dict) -> str:
    scored = _scored(results)
    by_id = _by_id(results)
    verdict = results["verdict"]
    settings = results["settings"]
    lines = [
        "\\newif\\ifMLSsynthetic",
        "\\MLSsynthetictrue" if results["synthetic"] else "\\MLSsyntheticfalse",
        _macro("GeneratedDate", tex_escape(results["generated_at"][:10])),
        _macro("RadiusKm", fmt(settings["radius_km"], 0)),
        _macro("AreaKm", fmt(settings["area_km2"], 0)),
        _macro("ClimatePeriod", tex_escape(settings["climate_period"])),
        _macro("WorldPopYear", settings["worldpop_year"]),
        _macro("SampleCap", settings["sample_size_cap"]),
        _macro("NumLocations", len(results["locations"])),
        _macro("NumScored", len(scored)),
        _macro("NumComponents", len(results["model"])),
    ]
    leader = by_id.get(verdict.get("leader_id"))
    lines.append(_macro("LeaderName", tex_escape(leader["name"]) if leader else "n/a"))
    lines.append(_macro("LeaderCountry", tex_escape(leader["country"]) if leader else "n/a"))
    lines.append(_macro("LeaderScore", fmt(leader["score"]) if leader else "--"))

    headline = verdict.get("headline")
    winner = by_id.get(headline["winner_id"]) if headline else None
    loser = by_id.get(headline["loser_id"]) if headline else None
    lines += [
        _macro("HeadlineWinner", tex_escape(winner["name"]) if winner else "n/a"),
        _macro("HeadlineLoser", tex_escape(loser["name"]) if loser else "n/a"),
        _macro("HeadlineWinnerScore", fmt(winner["score"]) if winner else "--"),
        _macro("HeadlineLoserScore", fmt(loser["score"]) if loser else "--"),
        _macro("HeadlineWinnerRank", winner["rank"] if winner else "--"),
        _macro("HeadlineLoserRank", loser["rank"] if loser else "--"),
        _macro("HeadlineMargin", fmt(headline["margin"]) if headline else "--"),
    ]
    bench = by_id.get(verdict.get("best_by_role", {}).get("benchmark"))
    lines += [
        _macro("BestBenchmarkName", tex_escape(bench["name"]) if bench else "n/a"),
        _macro("BestBenchmarkScore", fmt(bench["score"]) if bench else "--"),
        _macro("BestBenchmarkRank", bench["rank"] if bench else "--"),
    ]
    for key, color in results["palette"]["components"].items():
        lines.append(f"\\definecolor{{mls{key}}}{{HTML}}{{{color.lstrip('#').upper()}}}")
    return "\n".join(lines)


def ranking_table(results: dict) -> str:
    model = results["model"]
    scored = _scored(results)
    if not scored:
        return "\\emph{No location could be scored.}"
    cols = "rll" + "r" * (1 + len(model))
    head = ["\\#", "Location", "Country", "Score"] + [tex_escape(c["label"].split()[0]) for c in model]
    lines = [
        f"\\begin{{tabular}}{{@{{}}{cols}@{{}}}}",
        "\\toprule",
        " & ".join(head) + " \\\\",
        "\\midrule",
    ]
    for loc in scored:
        contrib = {c["key"]: c["contribution"] for c in loc["components"]}
        name = tex_escape(loc["name"])
        if loc["role"] == "headline":
            name = f"\\textbf{{{name}}}"
        elif loc["role"] == "benchmark":
            name = f"\\textit{{{name}}}"
        row = [str(loc["rank"]), name, tex_escape(loc["country"]), f"\\textbf{{{fmt(loc['score'])}}}"]
        row += [fmt(contrib.get(c["key"])) for c in model]
        lines.append(" & ".join(row) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines)


def headtohead_table(results: dict) -> str:
    headline = results["verdict"].get("headline")
    if not headline:
        return "\\emph{The head-to-head comparison is unavailable: both headline cities must be scored.}"
    by_id = _by_id(results)
    a, b = by_id[headline["winner_id"]], by_id[headline["loser_id"]]
    comp_b = {c["key"]: c for c in b["components"]}
    lines = [
        "\\begin{tabular}{lrr}",
        "\\toprule",
        f" & {tex_escape(a['name'])} & {tex_escape(b['name'])} \\\\",
        "\\midrule",
    ]
    for comp in a["components"]:
        other = comp_b[comp["key"]]
        lines.append(
            f"\\textbf{{{tex_escape(comp['label'])}}} (points of {fmt(comp['weight'] * 100)}) & "
            f"\\textbf{{{fmt(comp['contribution'])}}} & \\textbf{{{fmt(other['contribution'])}}} \\\\"
        )
        sub_b = {s["key"]: s for s in other["submetrics"]}
        for sub in comp["submetrics"]:
            lines.append(
                f"\\quad {tex_escape(sub['label'])} ({tex_escape(sub['unit'])}) & "
                f"{_raw(sub['raw'])} & {_raw(sub_b[sub['key']]['raw'])} \\\\"
            )
    lines += [
        "\\midrule",
        f"\\textbf{{Mushroom Livability Score}} & \\textbf{{{fmt(a['score'])}}} & \\textbf{{{fmt(b['score'])}}} \\\\",
        "\\bottomrule",
        "\\end{tabular}",
    ]
    return "\n".join(lines)


def _raw(value: Optional[float]) -> str:
    if value is None:
        return "--"
    if abs(value) >= 100:
        return fmt(value, 0)
    if abs(value) >= 1:
        return fmt(value, 2)
    return fmt(value, 3)


def model_table(results: dict) -> str:
    lines = [
        "\\begin{tabular}{@{}llrl@{}}",
        "\\toprule",
        "Component & Sub-metric & Weight & Scaling \\\\",
        "\\midrule",
    ]
    for comp in results["model"]:
        lines.append(f"\\textbf{{{tex_escape(comp['label'])}}} & & \\textbf{{{fmt(comp['weight'] * 100)}\\%}} & \\\\")
        for sub in comp["submetrics"]:
            lines.append(
                f" & {tex_escape(sub['label'])} & {fmt(comp['weight'] * sub['weight'] * 100)}\\% & "
                f"{tex_escape(sub['scaling'])} \\\\"
            )
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines)


def contributions_figure(results: dict, top_n: int = 12) -> str:
    scored = _scored(results)
    if not scored:
        return "\\emph{No data to plot.}"
    shown = scored[:top_n] + [l for l in scored[top_n:] if l["role"] == "headline"]
    scale = 0.085  # cm per score point
    bar_h, step = 0.34, 0.52
    lines = ["\\begin{tikzpicture}[font=\\footnotesize]"]
    for tick in range(0, 101, 20):
        x = tick * scale
        lines.append(f"\\draw[black!12] ({x:.3f},0.25) -- ({x:.3f},{-(len(shown) - 1) * step - 0.3:.3f});")
        lines.append(f"\\node[black!55, anchor=south] at ({x:.3f},0.25) {{{tick}}};")
    for index, loc in enumerate(shown):
        y = -index * step
        label = f"{loc['rank']}. {tex_escape(loc['name'])}"
        if loc["role"] == "headline":
            label = f"\\textbf{{{label}}}"
        lines.append(f"\\node[anchor=east] at (-0.1,{y:.3f}) {{{label}}};")
        x = 0.0
        for comp in loc["components"]:
            width = comp["contribution"] * scale
            if width > 0.005:
                lines.append(
                    f"\\fill[mls{comp['key']}] ({x:.3f},{y - bar_h / 2:.3f}) rectangle "
                    f"({x + max(width - 0.02, 0.005):.3f},{y + bar_h / 2:.3f});"
                )
            x += width
        lines.append(f"\\node[anchor=west] at ({x + 0.05:.3f},{y:.3f}) {{{fmt(loc['score'])}}};")
    legend_y = -(len(shown)) * step - 0.25
    for index, comp in enumerate(results["model"]):
        x = (index % 3) * 3.6
        y = legend_y - (index // 3) * 0.42
        lines.append(f"\\fill[mls{comp['key']}] ({x:.3f},{y - 0.1:.3f}) rectangle ({x + 0.25:.3f},{y + 0.1:.3f});")
        lines.append(f"\\node[anchor=west] at ({x + 0.28:.3f},{y:.3f}) {{{tex_escape(comp['label'])}}};")
    lines.append("\\end{tikzpicture}")
    return "\n".join(lines)


def findings(results: dict) -> str:
    """Factual sentences only - every clause is computed from the results."""
    scored = _scored(results)
    by_id = _by_id(results)
    verdict = results["verdict"]
    if not scored:
        return "No location could be scored; see the coverage notes."
    parts = []
    headline = verdict.get("headline")
    if headline:
        parts.append(tex_escape(headline["sentence"]))
        w, l = by_id[headline["winner_id"]], by_id[headline["loser_id"]]
        parts.append(
            f"Among all {len(scored)} scored locations, {tex_escape(w['name'])} ranks {_ordinal(w['rank'])} "
            f"and {tex_escape(l['name'])} ranks {_ordinal(l['rank'])}."
        )
    leader = by_id[verdict["leader_id"]]
    top = max(leader["components"], key=lambda c: c["contribution"])
    parts.append(
        f"The overall leader is {tex_escape(leader['name'])} ({tex_escape(leader['country'])}) with "
        f"{fmt(leader['score'])} points; its largest contribution comes from "
        f"{tex_escape(top['label'].lower())} ({fmt(top['contribution'])} points)."
    )
    bench = by_id.get(verdict.get("best_by_role", {}).get("benchmark"))
    if bench:
        parts.append(
            f"The best Canadian benchmark is {tex_escape(bench['name'])} with {fmt(bench['score'])} points "
            f"(rank {bench['rank']})."
        )
    return "\n".join(parts)


def coverage(results: dict) -> str:
    items = []
    for exclusion in results["exclusions"]:
        items.append(
            f"\\item The {tex_escape(exclusion['level'])} \\emph{{{tex_escape(exclusion['label'])}}} was excluded: "
            f"{tex_escape(exclusion['reason'])}."
        )
    for unscored in results["unscored"]:
        items.append(
            f"\\item {tex_escape(unscored['name'])} could not be scored (missing: "
            f"{tex_escape(', '.join(unscored['missing']))})."
        )
    failures = sum(len(l["errors"]) for l in results["locations"])
    if failures:
        items.append(f"\\item {failures} source request(s) failed across all locations; details are in the "
                     "results file under each location's \\texttt{errors} field.")
    if not items:
        return "All components and sub-metrics were available for every location; no exclusions were needed."
    return "\\begin{itemize}\n" + "\n".join(items) + "\n\\end{itemize}"


def _ordinal(n: int) -> str:
    suffix = "th" if 10 <= n % 100 <= 20 else {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")
    return f"{n}{suffix}"
